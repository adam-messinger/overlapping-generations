/** Pathogens in CDC's harmonized national respiratory-hospital panel. */
export type RespiratoryPathogen = 'covid19' | 'influenza' | 'rsv';

export interface RespiratoryObservation {
  weekEnding: string;
  covid19: number;
  influenza: number;
  rsv: number | null;
}

export interface RespiratorySeries {
  id: RespiratoryPathogen;
  label: string;
  family: string;
  weeks: readonly string[];
  admissions: readonly number[];
}

