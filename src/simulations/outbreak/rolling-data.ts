export const cdcRespiratoryObservations: readonly RespiratoryObservation[] =
  FROZEN_RESPIRATORY_CSV.split('\n').map((line) => {
    const [weekEnding, covid19, influenza, rsv] = line.split(',');
    return {
      weekEnding,
      covid19: Number(covid19),
      influenza: Number(influenza),
      rsv: rsv === '' ? null : Number(rsv),
    };
  });

const LABELS: Readonly<Record<RespiratoryPathogen, [string, string]>> = {
  covid19: ['COVID-19', 'coronavirus'],
  influenza: ['Influenza', 'orthomyxovirus'],
  rsv: ['RSV', 'pneumovirus'],
};

export function respiratorySeries(pathogen: RespiratoryPathogen): RespiratorySeries {
  const rows = cdcRespiratoryObservations.filter(
    (row) => pathogen !== 'rsv' || row.rsv !== null,
  );
  const [label, family] = LABELS[pathogen];
  return {
    id: pathogen,
    label,
    family,
    weeks: rows.map((row) => row.weekEnding),
    admissions: rows.map((row) => row[pathogen] as number),
  };
}

export const respiratoryPanel: readonly RespiratorySeries[] = (
  ['covid19', 'influenza', 'rsv'] as const
).map(respiratorySeries);
